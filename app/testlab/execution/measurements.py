"""What a technician can read out during a Test Run (M2A manual log).

The catalogue follows the run's configuration (arrangement, Plug Seal) and
reuses the monitored-parameter codes of the TCN (projects/arrangements.py),
so "Parameters to log" (instructed) and the manual log (actual) speak the
same language:

* common to every run: shaft speed and torque;
* Process Conditions — only with the Plug Seal, which establishes them
  (legacy log: "Plug FI/FO temp.", "Plug seal press. gauge reading");
* the seal-support circuit — Barrier (dual pressurized), Buffer (dual
  unpressurized) or Flush (single); for dual seals also the diff. seal
  pressure (head of the pumping device), offered only when the TCN ticks it
  in "Parameters to log";
* per seal position (Plug Seal, Test, Inboard, Outboard): face temperature
  and collected leakage.

Codes are stored with every value. A code that no longer applies after a
configuration change keeps its stored values and is still shown.
"""

from dataclasses import dataclass

from testlab.projects.arrangements import (
    DIFF_PRESSURE_PARAMETER,
    Arrangement,
    SealRole,
    applicable_monitored_parameters,
    seal_support_label,
)

VALUE = "value"
LEAKAGE = "leakage"

COMMON_GROUP = "Common"
PROCESS_GROUP = "Process"

# Common to every run, before the monitored parameters.
COMMON = [("speed", "Speed", "rpm"), ("torque", "Torque", "Nm")]
# Logged only when the TCN instructs it ("Parameters to log").
INSTRUCTED_ONLY = {DIFF_PRESSURE_PARAMETER}

_SUFFIXES = {
    "pressure": ("Pressure", "barg"),
    "inlet_temp": ("Inlet temp.", "°C"),
    "outlet_temp": ("Outlet temp.", "°C"),
    "flow": ("Flow", "l/min"),
    "face_temp": ("Face temp.", "°C"),
    "leakage": ("Leakage", "ml"),
}


@dataclass(frozen=True)
class Measurement:
    code: str
    group: str  # column group heading: "Common", "Process", "Barrier", "Inboard Seal", …
    label: str  # within the group: "Pressure", "Face temp.", …
    unit: str
    kind: str = VALUE  # LEAKAGE: collected volume; the rate is calculated
    description: str = ""

    @property
    def is_leakage(self):
        return self.kind == LEAKAGE

    @property
    def full_label(self):
        """e.g. "Barrier pressure [barg]", "Inboard Seal leakage [ml]"."""
        if self.group == COMMON_GROUP:
            return f"{self.label} [{self.unit}]"
        return f"{self.group} {self.label[0].lower()}{self.label[1:]} [{self.unit}]"


def _group(code, arrangement):
    if code.startswith("process_"):
        return PROCESS_GROUP
    if code.startswith("seal_support_"):
        return seal_support_label(arrangement)
    role = code.split("_", 1)[0]
    return SealRole(role).label


def measurement(code, arrangement):
    """Catalogue entry of a code, labelled for the run's arrangement."""
    for common_code, label, unit in COMMON:
        if code == common_code:
            return Measurement(code, COMMON_GROUP, label, unit)
    if code == DIFF_PRESSURE_PARAMETER:
        return Measurement(
            code, _group(code, arrangement), "Diff. seal pressure", "bar",
            description="Head generated by the pumping device in the seal",
        )
    for suffix, (label, unit) in _SUFFIXES.items():
        if code.endswith("_" + suffix):
            kind = LEAKAGE if suffix == "leakage" else VALUE
            return Measurement(code, _group(code, arrangement), label, unit, kind)
    raise ValueError(f"Unknown measurement code {code!r}")


def run_measurements(arrangement, plug_seal_present, instructed=()):
    """Measurements of a configuration, in column order; `instructed`: the TCN's parameters to log."""
    codes = [code for code, _, _ in COMMON]
    codes += [
        code for code in applicable_monitored_parameters(arrangement, plug_seal_present)
        if code not in INSTRUCTED_ONLY or code in instructed
    ]
    return [measurement(code, arrangement) for code in codes]


def is_known(code):
    try:
        measurement(code, Arrangement.SINGLE)
    except ValueError:
        return False
    return True
