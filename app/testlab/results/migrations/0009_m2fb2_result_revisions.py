def check_finals_are_recorded(apps, schema_editor):
    TestResult = apps.get_model("results", "TestResult")
    ResultRevision = apps.get_model("results", "ResultRevision")
    ReportDocument = apps.get_model("results", "ReportDocument")
    for result in TestResult.objects.filter(status="final").select_related("test_run"):
        where = f"M2F-B2 migration: the final Result of run {result.test_run_id}"
        revision = ResultRevision.objects.filter(result=result, number=0).first()
        if revision is None:
            raise RuntimeError(f"{where} has no revision 0; nothing was migrated.")
        with default_storage.open(revision.record_file.name, "rb") as stored:
            record = json.loads(gzip.decompress(stored.read()))
        if record != (result.final_snapshot or {}):
            raise RuntimeError(f"{where}: the record of revision 0 is not its final snapshot; nothing was migrated.")
        if not ReportDocument.objects.filter(revision__result=result, file=result.final_document.name,
                                             sha256=result.final_document_sha256).exists():
            raise RuntimeError(f"{where}: its final PDF is not a stored report document; nothing was migrated.")


