"""M2F-B2: revisions of a final Result.

* TestResult keeps the revision in progress (revision_reason, revision_opened_at/by); ResultRevision
  records why and by whom each later revision was opened (reason, opened_at/by).
* The M2E fields of TestResult (final_document, final_document_sha256, final_template_sha256,
  final_snapshot) are dropped: since M2F-B1 the record is the ResultRevision file and the PDF a
  ReportDocument. Before anything is dropped, every final Result is checked: its revision 0 record must
  equal final_snapshot and a stored document must be the final PDF (same file, same SHA-256). The
  migration stops, with nothing changed, when one does not. No file is touched.

Self-contained on purpose: it does not import application code that may change later.
"""

