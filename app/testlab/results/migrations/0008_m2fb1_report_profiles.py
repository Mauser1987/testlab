def _selections(apps):
    FaceMeasurement = apps.get_model("results", "FaceMeasurement")
    ReportSelection = apps.get_model("results", "ReportSelection")
    slots = {}
    for m in FaceMeasurement.objects.filter(reported=True, kind__in=["mahr", "roundpak"]).select_related(
            "component__result"):
        result = m.component.result
        found = slots.setdefault(result.pk, ({}, result))[0].setdefault(
            f"{m.component_id}:{m.kind}", {"detail": False, "figures": []})
        found["detail"] = found["detail"] or m.in_report_detail
        found["figures"] += [code for code in m.report_figures if code not in found["figures"]]
    for data, result in slots.values():
        ReportSelection.objects.create(result=result, profile="engineering", data={"slots": data},
                                       updated_by_id=result.updated_by_id)


