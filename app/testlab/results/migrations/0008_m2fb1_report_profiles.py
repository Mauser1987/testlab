def _sha(content):
    return hashlib.sha256(content).hexdigest()


def _read(name):
    with default_storage.open(name, "rb") as stored:
        return stored.read()


def _save(name, content, written):
    if default_storage.exists(name):
        if _read(name) != content:
            raise RuntimeError(f"M2F-B1 migration: {name} exists with other content; nothing was migrated.")
        return name
    saved = default_storage.save(name, ContentFile(content))
    written.append(saved)
    if saved != name or _read(saved) != content:
        raise RuntimeError(f"M2F-B1 migration: {name} was not stored correctly; nothing was migrated.")
    return saved


